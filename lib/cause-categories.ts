/**
 * 원인 도넛의 조각별 "최소 표시 각도 보장" 몫(전체 원 대비 비율).
 * 분류가 늘며 비중이 아주 작은 조각이 도넛에서 안 보이는 문제를 해결하기 위해,
 * 조각 arc 크기를 실제 건수 대신 이 함수의 표시용 비율로 그린다. 0.02 = 원의 2%
 * (≈7.2°, 링 중앙 기준 호 길이 ≈13px) → 흰 경계를 빼도 또렷이 보이는 최소 크기.
 */
export const CAUSE_MIN_SLICE_SHARE = 0.02;

/**
 * 원인 도넛 조각 최소 각도 보장 — 건수 배열 → 조각 arc 크기용 "표시 비율" 배열.
 *
 *   displayShare_i = m + (1 - n·m)·(count_i / total)   (count_i > 0)
 *   displayShare_i = 0                                  (count_i = 0, 조각 없음)
 *
 * 여기서 m = 조각당 최소 몫, n = 0건 초과 조각 수. 모든 조각이 ≥ m 이 되고 합은 1
 * 이라 별도 정규화가 필요 없다. 실제 비중이 m 보다 큰 큰 조각은 거의 그대로 그려지고
 * (왜곡 최소), 아주 작은 조각만 m 까지 끌어올려 보이게 만든다.
 *
 * 주의: 이 값은 arc 크기 전용이다. 툴팁·범례의 건수/비율은 반드시 실제 count 로
 * 표기해야 한다(그러지 않으면 3건이 30건처럼 보이는 왜곡이 노출된다).
 * 조각 수가 많아 n·m 이 과하면(원의 절반 초과) m 을 자동 축소해 큰 조각 붕괴를 막는다.
 */
export function causeDisplayShares(
  counts: number[],
  minShare: number = CAUSE_MIN_SLICE_SHARE,
): number[] {
  const total = counts.reduce((s, c) => s + Math.max(0, c), 0);
  if (total <= 0) return counts.map(() => 0);
  const nonZero = counts.filter((c) => c > 0).length;
  // 최소 몫 총합이 원의 절반을 넘지 않도록 가드(조각이 아주 많을 때).
  const m = Math.min(minShare, 0.5 / nonZero);
  const spread = 1 - m * nonZero;
  return counts.map((c) => (c > 0 ? m + spread * (c / total) : 0));
}
